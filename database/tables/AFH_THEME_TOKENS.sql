-- AFH_THEME_TOKENS: Appearance token catalogue and the installation's overrides.
-- TOKEN_VALUE NULL means "use the product default", which is written only in
-- apex/static/afh_theme.css as the var() fallback. See docs/decisions/007.
-- Kind: mutable. Generated per docs/architecture/database-conventions.md.
DECLARE
  l_cnt PLS_INTEGER;
BEGIN
  SELECT COUNT(*) INTO l_cnt FROM user_tables WHERE table_name = 'AFH_THEME_TOKENS';
  IF l_cnt = 0 THEN
    EXECUTE IMMEDIATE q'[
    CREATE TABLE afh_theme_tokens (
  token_id                   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  token_key                  VARCHAR2(40 CHAR) NOT NULL,
  css_property               VARCHAR2(60 CHAR) NOT NULL,
  category                   VARCHAR2(30 CHAR) NOT NULL,
  data_type                  VARCHAR2(20 CHAR) NOT NULL,
  token_value                VARCHAR2(200 CHAR),
  default_hint               VARCHAR2(200 CHAR),
  display_sequence           NUMBER DEFAULT 10 NOT NULL,
  description                VARCHAR2(400 CHAR),
  created_by                 VARCHAR2(255 CHAR) NOT NULL,
  creation_date              TIMESTAMP WITH LOCAL TIME ZONE NOT NULL,
  last_updated_by            VARCHAR2(255 CHAR) NOT NULL,
  last_update_date           TIMESTAMP WITH LOCAL TIME ZONE NOT NULL,
  CONSTRAINT AFH_THEME_TOKENS_PK PRIMARY KEY (token_id)
    )]';
  END IF;
END;
/
COMMENT ON TABLE afh_theme_tokens IS 'Appearance token catalogue and installation overrides; NULL token_value means the product default applies';
COMMENT ON COLUMN afh_theme_tokens.css_property IS 'The CSS custom property emitted by afh_theme_pkg.style_block, e.g. --afh-paper-2';
COMMENT ON COLUMN afh_theme_tokens.token_value IS 'Installation override; NULL means use the var() fallback in afh_theme.css';
COMMENT ON COLUMN afh_theme_tokens.default_hint IS 'Display-only copy of the stylesheet default, shown as placeholder text; never emitted';
