-- AFH_NOTIFICATIONS: In-app, e-mail and digest notification records
-- Kind: mutable. Generated per docs/architecture/database-conventions.md.
DECLARE
  l_cnt PLS_INTEGER;
BEGIN
  SELECT COUNT(*) INTO l_cnt FROM user_tables WHERE table_name = 'AFH_NOTIFICATIONS';
  IF l_cnt = 0 THEN
    EXECUTE IMMEDIATE q'[
    CREATE TABLE afh_notifications (
  notification_id            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  recipient_user_id          NUMBER NOT NULL,
  ticket_id                  NUMBER,
  event_code                 VARCHAR2(30 CHAR) NOT NULL,
  channel_code               VARCHAR2(30 CHAR) NOT NULL,
  state_code                 VARCHAR2(30 CHAR) NOT NULL,
  subject                    VARCHAR2(500 CHAR),
  body                       CLOB,
  delivery_attempts          NUMBER DEFAULT 0 NOT NULL,
  last_attempt_at            TIMESTAMP WITH LOCAL TIME ZONE,
  error_code                 VARCHAR2(30 CHAR),
  error_detail               VARCHAR2(2000 CHAR),
  digest_frequency           VARCHAR2(30 CHAR),
  read_at                    TIMESTAMP WITH LOCAL TIME ZONE,
  sent_at                    TIMESTAMP WITH LOCAL TIME ZONE,
  apex_mail_id               NUMBER,
  actor_user_id              NUMBER,
  task_id                    NUMBER,
  link_target                VARCHAR2(500 CHAR),
  created_by                 VARCHAR2(255 CHAR) NOT NULL,
  creation_date              TIMESTAMP WITH LOCAL TIME ZONE NOT NULL,
  last_updated_by            VARCHAR2(255 CHAR) NOT NULL,
  last_update_date           TIMESTAMP WITH LOCAL TIME ZONE NOT NULL,
  CONSTRAINT AFH_NOTIFICATIONS_PK PRIMARY KEY (notification_id)
    )
      LOB (body) STORE AS SECUREFILE]';
  END IF;
END;
/
-- Added 2026-09-06 (before any customer install): the APEX_MAIL id of a delivered e-mail, so
-- the worker can read the relay's verdict back from APEX_MAIL_LOG. Guarded for schemas that
-- were created from the earlier definition.
DECLARE
  l_cnt PLS_INTEGER;
BEGIN
  SELECT COUNT(*) INTO l_cnt FROM user_tab_columns
   WHERE table_name = 'AFH_NOTIFICATIONS' AND column_name = 'APEX_MAIL_ID';
  IF l_cnt = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE afh_notifications ADD (apex_mail_id NUMBER)';
  END IF;
END;
/
COMMENT ON TABLE afh_notifications IS 'In-app, e-mail and digest notification records';
COMMENT ON COLUMN afh_notifications.apex_mail_id IS 'APEX_MAIL id of the queued e-mail (EMAIL channel); joined to APEX_MAIL_LOG to reconcile the relay outcome';
