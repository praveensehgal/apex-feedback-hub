-- Indexes for AFH_WORKFLOW_TRANSITIONS
DECLARE
  l_cnt PLS_INTEGER;
BEGIN
  SELECT COUNT(*) INTO l_cnt FROM user_indexes WHERE index_name = 'AFH_WORKFLOW_TRANSITIONS_IX1';
  IF l_cnt = 0 THEN
    EXECUTE IMMEDIATE 'CREATE INDEX AFH_WORKFLOW_TRANSITIONS_IX1 ON afh_workflow_transitions (to_status_code)';
  END IF;
END;
/
