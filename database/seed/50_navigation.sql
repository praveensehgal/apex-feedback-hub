-- Seed: AFH_NAV_ENTRIES. Idempotent: a re-run refreshes every display attribute
-- (label, target, icon, sequence, audience, badge, parent) but NEVER touches
-- IS_ACTIVE, so a customer's disabled entries stay disabled across upgrades.
-- Parents are seeded before children (FK1 on parent_entry_code).
DECLARE
  PROCEDURE put(
    p_list_code    IN VARCHAR2,
    p_entry_code   IN VARCHAR2,
    p_label        IN VARCHAR2,
    p_display_seq  IN NUMBER,
    p_audience     IN VARCHAR2,
    p_page_no      IN NUMBER   DEFAULT NULL,
    p_icon_css     IN VARCHAR2 DEFAULT NULL,
    p_parent       IN VARCHAR2 DEFAULT NULL,
    p_target_type  IN VARCHAR2 DEFAULT 'PAGE',
    p_badge_source IN VARCHAR2 DEFAULT NULL) IS
  BEGIN
    MERGE INTO afh_nav_entries t
    USING (SELECT p_entry_code AS entry_code FROM dual) s
       ON (t.entry_code = s.entry_code)
     WHEN MATCHED THEN UPDATE
      SET t.list_code         = p_list_code,
          t.parent_entry_code = p_parent,
          t.label             = p_label,
          t.target_type       = p_target_type,
          t.page_no           = p_page_no,
          t.icon_css          = p_icon_css,
          t.display_seq       = p_display_seq,
          t.audience_code     = p_audience,
          t.badge_source      = p_badge_source
     WHEN NOT MATCHED THEN INSERT
          (list_code, entry_code, parent_entry_code, label, target_type, page_no,
           icon_css, display_seq, audience_code, badge_source)
   VALUES (p_list_code, p_entry_code, p_parent, p_label, p_target_type, p_page_no,
           p_icon_css, p_display_seq, p_audience, p_badge_source);
  END put;
